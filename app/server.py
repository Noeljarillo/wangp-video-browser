def _bundled_media_bins():
    """Wan2GP ships ffmpeg binaries in <launcher>/app/ffmpeg_bins - reuse them."""
    candidates = []
    api_dir = APP_DIR.parent.parent
    if api_dir.is_dir():
        candidates.extend(sorted(api_dir.glob("*/app/ffmpeg_bins")))
    return candidates


def resolve_media_tool(name):
    found = shutil.which(name)
    if found:
        return found
    exe = f"{name}.exe" if os.name == "nt" else name
    for folder in _bundled_media_bins():
        candidate = folder / exe
        if candidate.is_file():
            return str(candidate)
    return None


