def _iter_boxes(handle, start, end):
    """Yield (type, body_offset, box_end) for every ISO-BMFF box in a range."""
    pos = start
    while pos + 8 <= end:
        handle.seek(pos)
        header = handle.read(8)
        if len(header) < 8:
            return
        size = int.from_bytes(header[0:4], "big")
        box_type = header[4:8]
        body = pos + 8
        if size == 1:
            extended = handle.read(8)
            if len(extended) < 8:
                return
            size = int.from_bytes(extended, "big")
            body = pos + 16
        elif size == 0:
            size = end - pos
        if size < 8 or pos + size > end:
            return
        yield box_type, body, pos + size
        pos += size


def _find_comment_payload(handle, start, end, depth=0):
    if depth > 6:
        return None
    for box_type, body, box_end in _iter_boxes(handle, start, end):
        if box_type == b"\xa9cmt":
            for inner_type, inner_body, inner_end in _iter_boxes(handle, body, box_end):
                if inner_type == b"data":
                    # data box: 4 bytes type indicator + 4 bytes locale, then payload
                    handle.seek(inner_body + 8)
                    return handle.read(max(0, inner_end - (inner_body + 8)))
            continue
        if box_type in (b"moov", b"udta", b"ilst"):
            found = _find_comment_payload(handle, body, box_end, depth + 1)
            if found is not None:
                return found
        elif box_type == b"meta":
            # `meta` is a FullBox: skip its version/flags word before recursing.
            found = _find_comment_payload(handle, body + 4, box_end, depth + 1)
            if found is not None:
                return found
    return None


def _parse_metadata_text(text):
    if isinstance(text, bytes):
        text = text.decode("utf-8", errors="ignore")
    payload = str(text or "").replace("\ufeff", "").strip("\0").strip()
    if not payload:
        return None
    try:
        metadata = json.loads(payload)
    except (TypeError, ValueError):
        return None
    if isinstance(metadata, dict) and metadata.get(RESERVED_METADATA_KEY):
        return None
    return metadata if isinstance(metadata, dict) else None


def read_mp4_metadata(path):
    try:
        size = os.path.getsize(path)
        with open(path, "rb") as handle:
            payload = _find_comment_payload(handle, 0, size)
    except OSError:
        return None
    return _parse_metadata_text(payload) if payload else None


def read_container_metadata(path):
    """Fallback for MKV/WEBM (and odd MP4s): read the comment tag via ffprobe."""
    if not FFPROBE:
        return None
    try:
        result = subprocess.run(
            [FFPROBE, "-v", "error", "-show_entries", "format_tags", "-of", "json", str(path)],
            capture_output=True, text=True, encoding="utf-8", errors="ignore", timeout=30, check=False,
        )
        tags = ((json.loads(result.stdout or "{}") or {}).get("format") or {}).get("tags") or {}
    except (OSError, ValueError, subprocess.SubprocessError):
        return None
    for key in ("comment", "COMMENT", "description", "DESCRIPTION"):
        parsed = _parse_metadata_text(tags.get(key))
        if parsed:
            return parsed
    return None


def read_video_metadata(path):
    # Format detection + normalisation (WanGP, ComfyUI, ...) lives in metadata.py.
    return meta_reader.read_video_metadata(path, FFPROBE)


