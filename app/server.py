def _fraction(value):
    try:
        num, _, den = str(value).partition("/")
        den = float(den or 1)
        return round(float(num) / den, 4) if den else None
    except (TypeError, ValueError):
        return None


def probe_stream(path):
    if not FFPROBE:
        return {}
    try:
        result = subprocess.run(
            [FFPROBE, "-v", "error", "-show_entries",
             "format=duration,bit_rate:stream=codec_type,codec_name,width,height,r_frame_rate,nb_frames",
             "-of", "json", str(path)],
            capture_output=True, text=True, encoding="utf-8", errors="ignore", timeout=60, check=False,
        )
        parsed = json.loads(result.stdout or "{}") or {}
    except (OSError, ValueError, subprocess.SubprocessError):
        return {}

    streams = parsed.get("streams") or []
    fmt = parsed.get("format") or {}
    video = next((s for s in streams if s.get("codec_type") == "video"), None)
    audio = next((s for s in streams if s.get("codec_type") == "audio"), None)
    info = {
        "duration": _fraction(fmt.get("duration")),
        "bitrate": int(fmt["bit_rate"]) if str(fmt.get("bit_rate", "")).isdigit() else None,
        "has_audio": audio is not None,
        "audio_codec": (audio or {}).get("codec_name"),
    }
    if video:
        info.update({
            "width": video.get("width"),
            "height": video.get("height"),
            "fps": _fraction(video.get("r_frame_rate")),
            "codec": video.get("codec_name"),
            "frames": int(video["nb_frames"]) if str(video.get("nb_frames", "")).isdigit() else None,
        })
    return info


