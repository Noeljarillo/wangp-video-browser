def thumbnail_path(entry):
    if not FFMPEG:
        return None
    THUMB_DIR.mkdir(parents=True, exist_ok=True)
    target = THUMB_DIR / f"{entry['id']}_{int(entry['mtime'])}.jpg"
    if target.is_file() and target.stat().st_size > 0:
        return target
    duration = (entry.get("probe") or {}).get("duration") or 0
    seek = max(0.0, min(duration * 0.25, 2.0)) if duration else 0.0
    command = [
        FFMPEG, "-hide_banner", "-loglevel", "error", "-y",
        "-ss", f"{seek:.3f}", "-i", entry["path"],
        "-frames:v", "1", "-vf", "scale=480:-2", "-q:v", "5", str(target),
    ]
    try:
        subprocess.run(command, capture_output=True, timeout=60, check=False)
    except (OSError, subprocess.SubprocessError):
        return None
    return target if target.is_file() and target.stat().st_size > 0 else None


