def _pinokio_home():
    config = Path.home() / ".pinokio" / "config.json"
    try:
        home = (json.loads(config.read_text(encoding="utf-8")) or {}).get("home")
        if home and Path(home).is_dir():
            return Path(home)
    except (OSError, ValueError):
        pass
    env_home = os.environ.get("PINOKIO_HOME")
    return Path(env_home) if env_home and Path(env_home).is_dir() else None


def discover_roots():
    """Find every plausible WanGP outputs folder on this machine."""
    found = []

    def add(candidate):
        try:
            resolved = Path(candidate).expanduser().resolve()
        except (OSError, RuntimeError):
            return
        if resolved.is_dir() and resolved not in found:
            found.append(resolved)

    for entry in re.split(r"[;:]" if os.name != "nt" else ";", os.environ.get("WANGP_OUTPUTS", "")):
        if entry.strip():
            add(entry.strip())

    # Sibling launchers: <PINOKIO_HOME>/api/<launcher>/app/outputs
    api_dir = APP_DIR.parent.parent
    home = _pinokio_home()
    for base in ({api_dir} | ({home / "api"} if home else set())):
        if base and Path(base).is_dir():
            for outputs in sorted(Path(base).glob("*/app/outputs")):
                add(outputs)

    for saved in load_saved_roots():
        add(saved)
    return found


def load_saved_roots():
    try:
        return list(json.loads(ROOTS_FILE.read_text(encoding="utf-8")) or [])
    except (OSError, ValueError):
        return []


def save_root(path):
    roots = load_saved_roots()
    if path not in roots:
        roots.append(path)
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    ROOTS_FILE.write_text(json.dumps(roots, indent=2), encoding="utf-8")


def forget_root(path):
    roots = [r for r in load_saved_roots() if r != path]
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    ROOTS_FILE.write_text(json.dumps(roots, indent=2), encoding="utf-8")


def video_id(path):
    return sha1(str(path).encode("utf-8")).hexdigest()[:16]


def _load_cache():
    try:
        return json.loads(INDEX_FILE.read_text(encoding="utf-8")) or {}
    except (OSError, ValueError):
        return {}


def _save_cache(entries):
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    payload = {entry["cache_key"]: entry for entry in entries}
    try:
        INDEX_FILE.write_text(json.dumps(payload), encoding="utf-8")
    except OSError:
        pass


FILENAME_PATTERN = re.compile(
    r"^(?P<date>\d{4}-\d{2}-\d{2})-(?P<time>\d{2}h\d{2}m\d{2}s)_seed(?P<seed>\d+)_(?P<rest>.*)$"
)


def parse_filename(name):
    match = FILENAME_PATTERN.match(Path(name).stem)
    if not match:
        return {}
    tags = re.search(r"\[(?P<tags>[^\]]*)\]", match.group("rest") or "")
    return {
        "date": match.group("date"),
        "time": match.group("time").replace("h", ":").replace("m", ":").rstrip("s"),
        "seed": int(match.group("seed")),
        "tags": tags.group("tags") if tags else "",
    }


def build_entry(path, root, cache):
    stat = path.stat()
    cache_key = f"{path}|{stat.st_size}|{int(stat.st_mtime_ns)}|m{meta_reader.META_VERSION}"
    cached = cache.get(cache_key)
    if cached:
        entry = dict(cached)
    else:
        entry = {
            "cache_key": cache_key,
            "meta": read_video_metadata(path),
            "probe": probe_stream(path),
        }
    entry.update({
        "id": video_id(path),
        "name": path.name,
        "path": str(path),
        "root": str(root),
        "rel": str(path.relative_to(root)),
        "size": stat.st_size,
        "mtime": stat.st_mtime,
        "filename_info": parse_filename(path.name),
    })
    if not entry.get("cid"):
        entry["cid"] = library.content_id(path, stat.st_size)
    return entry


def scan(roots):
    cache = _load_cache()
    files = []
    seen = set()
    # Roots may be nested (e.g. `app` and `app/outputs`); index each file once,
    # attributing it to the first - i.e. most specific - root that matched.
    for root in sorted(roots, key=lambda r: len(str(r)), reverse=True):
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIR_NAMES and not d.startswith(".")]
            for filename in filenames:
                if not filename.lower().endswith(VIDEO_EXTENSIONS) or filename.startswith("."):
                    continue
                path = Path(dirpath) / filename
                if path in seen:
                    continue
                seen.add(path)
                files.append((path, root))

    entries = []
    with ThreadPoolExecutor(max_workers=min(8, (os.cpu_count() or 2) * 2)) as pool:
        futures = [pool.submit(build_entry, path, root, cache) for path, root in files]
        for future in futures:
            try:
                entries.append(future.result())
            except (OSError, ValueError) as error:
                print(f"[wangp-video-browser] skipped a file: {error}", file=sys.stderr)

    entries.sort(key=lambda item: item["mtime"], reverse=True)
    _save_cache(entries)
    return entries


def refresh_index(roots=None):
    with _index_lock:
        active_roots = roots if roots is not None else [Path(r) for r in _index["roots"]] or discover_roots()
        entries = scan(active_roots)
        _index["videos"] = entries
        _index["roots"] = [str(r) for r in active_roots]
        _index["scanned_at"] = time.time()
        _queue_analysis(entries)
        return dict(_index)


def public_entry(entry):
    return dict({k: v for k, v in entry.items() if k != "cache_key"}, lib=library.get(entry.get("cid")))


# Live watch folder (P1.5): new renders are indexed incrementally and pushed
# to the UI over SSE (GET /events).
events = watcher.EventHub()


def apply_changes(added, removed):
    cache = _load_cache()
    with _index_lock:
        known = {v["path"] for v in _index["videos"]}
    fresh = []
    for path, root in added:
        if path in known:
            continue
        try:
            fresh.append(build_entry(Path(path), Path(root), cache))
        except (OSError, ValueError) as error:
            print(f"[wangp-video-browser] skipped a file: {error}", file=sys.stderr)
    gone = set(removed)
    with _index_lock:
        removed_ids = [v["id"] for v in _index["videos"] if v["path"] in gone]
        videos = [v for v in _index["videos"] if v["path"] not in gone] + fresh
        videos.sort(key=lambda item: item["mtime"], reverse=True)
        _index["videos"] = videos
        _save_cache(videos)
    if fresh:
        _queue_analysis(fresh)
    if fresh or removed_ids:
        events.publish({"type": "change", "added": [public_entry(e) for e in fresh], "removed": removed_ids})


def current_roots():
    with _index_lock:
        return list(_index["roots"])
def _queue_analysis(entries):
    try:  # optional add-on (C2): never let it break indexing
        analysis_host.enqueue_entries(entries)
    except Exception as error:  # noqa: BLE001
        print(f"[wangp-video-browser] analysis queue skipped: {error}", file=sys.stderr)


def find_video(video_id_value):
    with _index_lock:
        return next((v for v in _index["videos"] if v["id"] == video_id_value), None)


