class Handler(BaseHTTPRequestHandler):
    server_version = "WanVideoBrowser/1.0"
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):
        if os.environ.get("WANGP_BROWSER_VERBOSE"):
            super().log_message(fmt, *args)

    # -- helpers ------------------------------------------------------------
    def _send_json(self, payload, status=200):
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _send_bytes(self, body, content_type, cache="private, max-age=3600", headers=None):
        self.send_response(200)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", cache)
        for name, value in (headers or {}).items():
            self.send_header(name, value)
        self.end_headers()
        self.wfile.write(body)

    def _send_file(self, path, content_type=None, cache="no-store", headers=None):
        path = Path(path)
        if not path.is_file():
            return self._send_json({"error": "not found"}, 404)
        content_type = content_type or mimetypes.guess_type(str(path))[0] or "application/octet-stream"
        size = path.stat().st_size
        start, end = 0, size - 1
        status = 200
        range_header = self.headers.get("Range")
        if range_header:
            match = re.match(r"bytes=(\d*)-(\d*)", range_header.strip())
            if match:
                raw_start, raw_end = match.groups()
                if raw_start:
                    start = int(raw_start)
                    end = int(raw_end) if raw_end else size - 1
                elif raw_end:  # suffix range: bytes=-N
                    start = max(0, size - int(raw_end))
                if start >= size:
                    self.send_response(416)
                    self.send_header("Content-Range", f"bytes */{size}")
                    self.send_header("Content-Length", "0")
                    self.end_headers()
                    return None
                end = min(end, size - 1)
                status = 206

        length = end - start + 1
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(length))
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Cache-Control", cache)
        if status == 206:
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        for name, value in (headers or {}).items():
            self.send_header(name, value)
        self.end_headers()
        try:
            with open(path, "rb") as handle:
                handle.seek(start)
                remaining = length
                while remaining > 0:
                    chunk = handle.read(min(256 * 1024, remaining))
                    if not chunk:
                        break
                    self.wfile.write(chunk)
                    remaining -= len(chunk)
        except (BrokenPipeError, ConnectionResetError):
            pass
        return None

    def _public_index(self):
        with _index_lock:
            return {
                "videos": [public_entry(entry) for entry in _index["videos"]],
                "roots": list(_index["roots"]),
                "scanned_at": _index["scanned_at"],
                "ffmpeg": bool(FFMPEG),
                "ffprobe": bool(FFPROBE),
            }

    # -- routes -------------------------------------------------------------
    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        route = parsed.path

        if route in ("/", "/index.html"):
            return self._send_file(WEB_DIR / "index.html", "text/html; charset=utf-8")

        if route == "/api/videos":
            return self._send_json(self._public_index())

        if route == "/events":
            return watcher.serve_sse(self, events)
        if route == "/api/analysis/status":
            return self._send_json(analysis_host.status())
        if route.startswith("/api/analysis/detections/"):
            entry = find_video(route[len("/api/analysis/detections/"):])
            return self._send_json(detections_api.detections(entry)) if entry else self._send_json({"error": "unknown video"}, 404)
        if route == "/api/characters":
            with _index_lock:
                entries = list(_index["videos"])
            return self._send_json(characters_api.listing(entries))
        if route.startswith("/api/characters/avatar/"):
            avatar = characters_api.avatar_path(route[len("/api/characters/avatar/"):])
            return self._send_file(avatar, "image/jpeg", cache="no-cache") if avatar else self._send_json({"error": "not found"}, 404)
        if route.startswith("/api/analysis/crop/"):
            vid, _, n_text = route[len("/api/analysis/crop/"):].partition("/")
            crop = detections_api.crop_path(find_video(vid), n_text)
            return self._send_file(crop, "image/jpeg", cache="private, max-age=86400") if crop else self._send_json({"error": "not found"}, 404)
        if route == "/api/semantic/search":
            with _index_lock:
                by_path = {v["path"]: v for v in _index["videos"]}
            q = urllib.parse.parse_qs(parsed.query).get("q", [""])[0]
            return self._send_json(semantic_host.search(q, by_path))
        if route == "/api/defects":
            with _index_lock:
                entries = list(_index["videos"])
            return self._send_json(defects_host.payload(entries))
        if route == "/api/tags":
            with _index_lock:
                entries = list(_index["videos"])
            return self._send_json(tags_host.payload(entries))

        if route == "/api/rescan":
            refresh_index()
            return self._send_json(self._public_index())

        if route.startswith("/media/"):
            entry = find_video(route[len("/media/"):])
            if not entry:
                return self._send_json({"error": "unknown video"}, 404)
            return self._send_file(entry["path"], cache="private, max-age=3600")

        if route.startswith("/thumb/"):
            entry = find_video(route[len("/thumb/"):])
            if not entry:
                return self._send_json({"error": "unknown video"}, 404)
            thumb = thumbnail_path(entry)
            if not thumb:
                return self._send_json({"error": "no thumbnail"}, 404)
            return self._send_file(thumb, "image/jpeg", cache="private, max-age=86400")

        if route.startswith("/api/inputs/"):
            entry = find_video(route[len("/api/inputs/"):])
            if not entry:
                return self._send_json({"error": "unknown video"}, 404)
            return self._send_json({"id": entry["id"], "inputs": inputs.public(inputs.collect(entry))})

        if route.startswith("/input/"):
            # Allow-list only: /input/<id>/<n>, where n indexes this clip's own refs.
            vid, _, n_text = route[len("/input/"):].partition("/")
            ref = inputs.lookup(find_video(vid), n_text)
            if not ref:
                return self._send_json({"error": "not found"}, 404)
            if ref["source"] == "embedded":
                return self._send_bytes(inputs.read_embedded(ref), ref["_mime"])
            return self._send_file(ref["_path"], cache="private, max-age=3600")

        if route.startswith("/api/export/"):
            entry = find_video(route[len("/api/export/"):])
            if not entry:
                return self._send_json({"error": "unknown video"}, 404)
            new_seed = urllib.parse.parse_qs(parsed.query).get("new_seed", ["0"])[0] in ("1", "true")
            try:
                body, name = export_settings.export(entry, new_seed=new_seed)
            except export_settings.NotExportable as error:
                return self._send_json({"error": str(error)}, 400)
            return self._send_bytes(body, "application/json; charset=utf-8", cache="no-store",
                                    headers={"Content-Disposition": f'attachment; filename="{name}"'})

        if route.startswith("/api/compare/job/"):
            job = export_compare.get_job(route[len("/api/compare/job/"):])
            return self._send_json(job) if job else self._send_json({"error": "unknown job"}, 404)

        if route.startswith("/exports/"):
            target = export_compare.export_path(route[len("/exports/"):])
            if not target:
                return self._send_json({"error": "not found"}, 404)
            return self._send_file(target, cache="private, max-age=3600",
                                   headers={"Content-Disposition": f'attachment; filename="{target.name}"'})
        if route.startswith("/filmstrip/"):
            entry = find_video(route[len("/filmstrip/"):])
            if not entry:
                return self._send_json({"error": "unknown video"}, 404)
            status, sprite = filmstrips.status(entry)
            if sprite:
                return self._send_file(sprite, "image/jpeg", cache="private, max-age=86400")
            return self._send_json({"status": status, "fallback": "poster"}, 202 if status == "queued" else 404)

        if route.startswith("/static/"):
            target = (WEB_DIR / route[len("/static/"):]).resolve()
            if WEB_DIR.resolve() in target.parents:
                # Fonts never change without changing filename, so they can be
                # cached hard. The stylesheet and script must not be, or an
                # updated launcher would keep serving yesterday's UI.
                immutable = target.suffix.lower() in (".woff2", ".woff", ".ttf", ".png", ".svg")
                cache = "private, max-age=86400, immutable" if immutable else "no-cache"
                return self._send_file(target, cache=cache)
            return self._send_json({"error": "forbidden"}, 403)

        return self._send_json({"error": "not found"}, 404)

    def do_POST(self):
        parsed = urllib.parse.urlparse(self.path)
        try:
            length = int(self.headers.get("Content-Length") or 0)
            payload = json.loads(self.rfile.read(length) or b"{}")
        except (TypeError, ValueError):
            payload = {}

        if parsed.path == "/api/roots/add":
            candidate = Path(str(payload.get("path", "")).strip()).expanduser()
            if not candidate.is_dir():
                return self._send_json({"error": f"not a folder: {candidate}"}, 400)
            resolved = str(candidate.resolve())
            save_root(resolved)
            with _index_lock:
                roots = [Path(r) for r in _index["roots"]]
            if Path(resolved) not in roots:
                roots.append(Path(resolved))
            refresh_index(roots)
            return self._send_json(self._public_index())

        if parsed.path == "/api/roots/remove":
            target = str(payload.get("path", "")).strip()
            forget_root(target)
            with _index_lock:
                roots = [Path(r) for r in _index["roots"] if r != target]
            refresh_index(roots)
            return self._send_json(self._public_index())

        if parsed.path == "/api/characters/action":
            with _index_lock:
                entries = list(_index["videos"])
            try:
                return self._send_json(characters_api.action(payload, entries))
            except (TypeError, ValueError) as error:
                return self._send_json({"error": str(error)}, 400)
        if parsed.path == "/api/characters/recluster":
            return self._send_json(characters_api.recluster())

        if parsed.path.startswith("/api/library/"):
            return self._library_route(parsed.path, payload)

        if parsed.path == "/api/compare/export":
            ids = payload.get("ids") if isinstance(payload.get("ids"), list) else []
            entries = [e for e in (find_video(str(i)) for i in ids) if e]
            try:
                job = export_compare.submit(FFMPEG, entries, kind=payload.get("kind") or "video",
                                            mode=payload.get("mode") or "side", fmt=payload.get("format") or "mp4",
                                            wipe=payload.get("wipe", 50))
            except (export_compare.ExportError, TypeError, ValueError) as error:
                return self._send_json({"error": str(error)}, 400)
            return self._send_json(job)

        return self._send_json({"error": "not found"}, 404)

    def _library_route(self, route, payload):
        ids = payload.get("ids") if isinstance(payload.get("ids"), list) else []
        entries = [entry for entry in (find_video(str(i)) for i in ids) if entry and entry.get("cid")]
        if not entries:
            return self._send_json({"error": "no known clips in ids"}, 400)
        if route == "/api/library/update":
            try:
                items = library.update([e["cid"] for e in entries], payload.get("patch"))
            except ValueError as error:
                return self._send_json({"error": str(error)}, 400)
            return self._send_json({"items": {e["id"]: items[e["cid"]] for e in entries}})
        if route == "/api/library/trash":
            # Only clips the user rejected can be trashed, and only to the OS trash (C4).
            moved, errors = [], []
            for entry in entries:
                if library.get(entry["cid"]).get("status") != "reject":
                    errors.append({"id": entry["id"], "error": "not rejected"})
                    continue
                try:
                    library.move_to_trash(entry["path"])
                    moved.append(entry["id"])
                except (OSError, subprocess.SubprocessError) as error:
                    errors.append({"id": entry["id"], "error": str(error)})
            refresh_index()
            return self._send_json(dict(self._public_index(), moved=moved, errors=errors))
        return self._send_json({"error": "not found"}, 404)


def main():
    parser = argparse.ArgumentParser(description="Browse and compare WanGP video outputs")
    parser.add_argument("--port", type=int, default=int(os.environ.get("WANGP_BROWSER_PORT", 7899)))
    parser.add_argument("--host", default=os.environ.get("WANGP_BROWSER_HOST", "127.0.0.1"))
    parser.add_argument("--root", action="append", default=[], help="outputs folder to index (repeatable)")
    args = parser.parse_args()

    roots = [Path(r).expanduser().resolve() for r in args.root if Path(r).expanduser().is_dir()] or discover_roots()
    if not roots:
        print("[wangp-video-browser] No outputs folder found yet - add one from the web UI.")
    for root in roots:
        print(f"[wangp-video-browser] indexing {root}")

    # Claim the port before indexing. Pinokio hands out "the next free port" to
    # every app it starts, so a port left unbound while a large outputs folder is
    # indexed can be handed to Wan2GP as well. A fixed default outside Pinokio's
    # range, with a short fallback walk if it is taken, avoids both problems.
    server = None
    for port in range(args.port, args.port + 20):
        try:
            server = ThreadingHTTPServer((args.host, port), Handler)
            break
        except OSError:
            print(f"[wangp-video-browser] port {port} is busy, trying {port + 1}")
    if server is None:
        sys.exit(f"[wangp-video-browser] no free port in {args.port}-{args.port + 19}")
    server.daemon_threads = True

    analysis_host.start(FFMPEG)
    refresh_index(roots)
    with _index_lock:
        count = len(_index["videos"])
    print(f"[wangp-video-browser] indexed {count} video(s)"
          f"{'' if FFMPEG else ' (ffmpeg not found - thumbnails disabled)'}")

    watcher.FolderWatcher(current_roots, apply_changes, VIDEO_EXTENSIONS, SKIP_DIR_NAMES).start()
    print(f"[wangp-video-browser] Running at http://{args.host}:{server.server_address[1]}", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n[wangp-video-browser] shutting down")
    finally:
        server.server_close()
        analysis_host.stop()


if __name__ == "__main__":
    main()
